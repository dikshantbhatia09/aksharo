function generateWaveform(seed: number, count: number = 60): string {
  const peaks: number[] = [];
  let prev = 0.3;
  for (let i = 0; i < count; i++) {
    // Deterministic pseudo-random variation
    const noise = Math.sin(seed * 997 + i * 13.37) * 0.5 + 0.5;
    const value = Math.max(0.08, Math.min(0.98, prev * 0.4 + noise * 0.6));
    peaks.push(Math.round(value * 100) / 100);
    prev = value;
  }
  return JSON.stringify(peaks);
}

