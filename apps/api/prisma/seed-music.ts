export async function seedMusicTracks(prisma: PrismaClient): Promise<number> {
  let seededCount = 0;
  for (const track of SEED_TRACKS) {
    await prisma.musicTrack.upsert({
      where: { id: track.id },
      create: {
        id: track.id,
        title: track.title,
        artist: track.artist,
        mood: track.mood,
        tempo: track.tempo,
        bpm: track.bpm,
        durationSec: track.durationSec,
        previewUri: track.previewUri,
        masterUri: track.masterUri,
        waveformJson: track.waveformJson,
        isPublic: track.isPublic,
      },
      update: {
        title: track.title,
        artist: track.artist,
        mood: track.mood,
        tempo: track.tempo,
        bpm: track.bpm,
        durationSec: track.durationSec,
        previewUri: track.previewUri,
        masterUri: track.masterUri,
        waveformJson: track.waveformJson,
        isPublic: track.isPublic,
      },
    });
    seededCount++;
  }
  return seededCount;
}

if (process.argv[1] && process.argv[1].includes("seed-music")) {
  const prisma = new PrismaClient();
  seedMusicTracks(prisma)
    .then((count) => {
      console.log(`[seed-music] Successfully seeded ${count} royalty-free music tracks.`);
      return prisma.$disconnect();
    })
    .catch((err) => {
      console.error("[seed-music] Error seeding music tracks:", err);
      return prisma.$disconnect().finally(() => process.exit(1));
    });
}
