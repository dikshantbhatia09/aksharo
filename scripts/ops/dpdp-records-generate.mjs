#!/usr/bin/env node
/**
 * Generates `docs/compliance/dpdp-records.md` — the DPDP "record of processing
 * activities" (X04 §5) — from the Prisma schema and
 * `docs/compliance/dpdp-records.manifest.json`, and fails when a table the
 * schema says holds personal data has no manifest entry.
 *
 *   node scripts/ops/dpdp-records-generate.mjs          # (re)write the doc
 *   node scripts/ops/dpdp-records-generate.mjs --check  # fail if it would change, or if the manifest is incomplete
 *
 * **How "holds personal data" is detected.** A model is treated as
 * personal-data-bearing when its body contains a direct Prisma relation field
 * typed `User` or `Workspace` — i.e. `owner User @relation(...)` or
 * `workspace Workspace @relation(...)`. This is deliberately a wide net: DPDP's
 * definition of personal data is broad, and a model scoped to a workspace
 * (owned by a person) or a user is personal data until proven otherwise, not
 * the reverse. `ops_incidents`/`ops_status_snapshots` (this same work
 * package) correctly fall outside it — neither relates to a user or
 * workspace, because a status-page incident is about the platform, not a
 * person. A model with neither relation (system-wide config, catalogue data)
 * is out of scope for this generator, same reasoning.
 *
 * The manifest is hand-maintained on purpose: purpose and retention are
 * product/legal decisions, not something a script should guess. This script's
 * only job is to make forgetting to update the manifest a CI failure.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import * as prettier from "prettier";

const REPO_ROOT = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const SCHEMA_PATH = join(REPO_ROOT, "apps/api/prisma/schema.prisma");
const MANIFEST_PATH = join(REPO_ROOT, "docs/compliance/dpdp-records.manifest.json");
const DOC_PATH = join(REPO_ROOT, "docs/compliance/dpdp-records.md");

const CHECK = process.argv.includes("--check");

/** @returns {{name: string, table: string | null, touchesUser: boolean, touchesWorkspace: boolean}[]} */
export function parseModels(schemaText) {
  const modelRe = /^model\s+(\w+)\s*\{/gm;
  const models = [];
  let match;
  while ((match = modelRe.exec(schemaText)) !== null) {
    const bodyStart = match.index + match[0].length;
    const closeIndex = schemaText.indexOf("\n}", bodyStart);
    const body = schemaText.slice(bodyStart, closeIndex === -1 ? undefined : closeIndex);
    const mapMatch = /@@map\("([^"]+)"\)/.exec(body);
    models.push({
      name: match[1],
      table: mapMatch?.[1] ?? null,
      touchesUser: /\bUser(\?|\[\])?\s+@relation/.test(body),
      touchesWorkspace: /\bWorkspace(\?|\[\])?\s+@relation/.test(body),
    });
  }
  return models;
}

export function personalDataTables(models) {
  return models
    .filter((m) => m.table !== null && (m.touchesUser || m.touchesWorkspace))
    .map((m) => ({ ...m, table: /** @type {string} */ (m.table) }));
}

export function renderMarkdown(manifest, tables) {
  const rows = tables
    .slice()
    .sort((a, b) => a.table.localeCompare(b.table))
    .map((t) => {
      const entry = manifest.tables[t.table];
      const scope = [t.touchesUser ? "user" : null, t.touchesWorkspace ? "workspace" : null]
        .filter(Boolean)
        .join(" + ");
      return `| \`${t.table}\` | ${scope} | ${entry.purpose} | ${entry.retention} |`;
    })
    .join("\n");

  return `# DPDP records of processing activities

Generated by \`scripts/ops/dpdp-records-generate.mjs\` from
\`apps/api/prisma/schema.prisma\` and
\`docs/compliance/dpdp-records.manifest.json\` — **do not hand-edit this file**;
edit the manifest and regenerate. CI (\`.github/workflows/ops-dpdp-records.yml\`)
fails if this file would change (someone forgot to regenerate) or if the
manifest is missing an entry for a table the schema now says holds personal
data (someone forgot to add one).

Manifest version: ${manifest.version}.

Every table below is detected as personal-data-bearing because it carries a
direct Prisma relation to \`User\` or \`Workspace\`. "Purpose" is the
\`ConsentPurpose\` it falls under (\`service\` for essential processing per D61,
which is never gated behind a consent toggle); "Retention" is transcribed from
the manifest, which is the actual product/legal decision.

| Table | Linked via | Purpose | Retention |
|---|---|---|---|
${rows}

## Purposes, for reference

From \`apps/api/prisma/schema.prisma\`'s \`ConsentPurpose\` enum and
\`apps/api/src/privacy/privacy-notice.ts\`: \`analytics\`, \`memory\`,
\`marketing\`, \`share_upload\`, \`affiliate\` are optional, per-purpose,
granular consent (D61 Rule 3); \`service\` (used above for every table that
backs the product itself) is essential and is never asked for, because the
product cannot run without it.
`;
}

async function main() {
  const schemaText = readFileSync(SCHEMA_PATH, "utf8");
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  const models = parseModels(schemaText);
  const tables = personalDataTables(models);

  const missing = tables.filter((t) => manifest.tables[t.table] === undefined);
  const incomplete = tables
    .filter((t) => manifest.tables[t.table] !== undefined)
    .filter((t) => {
      const entry = manifest.tables[t.table];
      return (
        typeof entry.purpose !== "string" ||
        entry.purpose.trim() === "" ||
        typeof entry.retention !== "string" ||
        entry.retention.trim() === ""
      );
    });

  if (missing.length > 0 || incomplete.length > 0) {
    console.error("[dpdp-records] Personal-data tables missing a manifest entry:");
    for (const t of missing) console.error(`  - ${t.table} (model ${t.name})`);
    for (const t of incomplete)
      console.error(`  - ${t.table} (model ${t.name}) — empty purpose/retention`);
    console.error(
      `\nAdd an entry to ${MANIFEST_PATH.replace(REPO_ROOT + "/", "").replace(REPO_ROOT + "\\", "")} for each, ` +
        "with a real purpose and retention decision, then re-run this script.",
    );
    process.exitCode = 1;
    return;
  }

  // Run through Prettier so the file on disk matches what `pnpm format:changed`
  // would produce — otherwise the two checks fight (the generator says clean,
  // then `format:changed:check` rewrites a markdown-table column width and the
  // generator says dirty again).
  const rawRendered = renderMarkdown(manifest, tables);
  const prettierOptions = (await prettier.resolveConfig(DOC_PATH)) ?? {};
  const rendered = await prettier.format(rawRendered, { ...prettierOptions, filepath: DOC_PATH });

  if (CHECK) {
    let current;
    try {
      current = readFileSync(DOC_PATH, "utf8");
    } catch {
      current = null;
    }
    if (current !== rendered) {
      console.error(
        `[dpdp-records] ${DOC_PATH} is out of date. Run node scripts/ops/dpdp-records-generate.mjs and commit the result.`,
      );
      process.exitCode = 1;
      return;
    }
    console.log("[dpdp-records] up to date.");
    return;
  }

  writeFileSync(DOC_PATH, rendered, "utf8");
  console.log(`[dpdp-records] wrote ${DOC_PATH} (${String(tables.length)} tables).`);
}

// Only run as a CLI, not when a test imports this module for its exports.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
